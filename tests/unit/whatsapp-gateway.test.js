import { mkdtempSync, readFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { WhatsAppGateway } from '../../src/gateway/whatsapp.js';
import { ClonePipeline } from '../../src/pipeline/clone.js';

const JID = '5511999990000@s.whatsapp.net';

const incoming = (text, id, pushName = 'Maria') => ({
    key: { remoteJid: JID, fromMe: false, id },
    pushName,
    message: { conversation: text },
});
const own = (text, id) => ({
    key: { remoteJid: JID, fromMe: true, id },
    message: { conversation: text },
});

describe('WhatsAppGateway — passive listening, triggers, JIT personality', () => {
    let root;
    let dataDir;
    let gw;
    let sock;
    let brain;

    const readJson = (name) => JSON.parse(readFileSync(join(dataDir, name), 'utf-8'));

    beforeEach(() => {
        root = mkdtempSync(join(tmpdir(), 'openself-gw-'));
        dataDir = join(root, 'data');
        brain = {
            generate: vi.fn(async (system) =>
                /analista de personalidade/i.test(system)
                    ? 'ok: {"relationship":"amigo","rules":"seja leve","avgReplyWords":6,"formality":"casual"}'
                    : 'beleza',
            ),
        };
        const pipeline = new ClonePipeline({ dataDir, config: {} });
        pipeline.setBrain(brain);
        gw = new WhatsAppGateway({
            dataDir,
            sessionDir: join(dataDir, 'whatsapp-session'),
            pipeline,
            ghost: { getStatus: () => ({ ghostMode: false }), shouldCloneReply: () => true },
        });
        pipeline.setMemory(gw.conversationMemory, gw.chatMemory);
        sock = {
            user: { id: 'me@s.whatsapp.net' },
            readMessages: vi.fn(async () => {}),
            presenceSubscribe: vi.fn(async () => {}),
            sendPresenceUpdate: vi.fn(async () => {}),
            sendMessage: vi.fn(async () => ({ key: { id: 'BOT-' + Math.random() } })),
        };
        gw.sock = sock;
        gw.sleep = async () => {};
        gw.now = () => new Date('2026-10-14T15:00:00Z'); // 12:00 America/Sao_Paulo
        gw.batchMaxMs = 0; // batching off by default: one reply per message (legacy behaviour)
    });

    afterEach(() => rmSync(root, { recursive: true, force: true }));

    it('learns every incoming message but stays mute by default (unknown contact, no trigger)', async () => {
        await gw.handleMessage(incoming('oi, tudo bem?', 'A1'));

        expect(sock.sendMessage).not.toHaveBeenCalled();
        const memories = await gw.chatMemory.findRelevant('', 'Maria', 10);
        expect(memories.map((m) => m.theirMessage)).toContain('oi, tudo bem?');
        expect(gw.contacts.Maria).toBeUndefined();
    });

    it('keeps RAG isolated per contact', async () => {
        await gw.handleMessage(incoming('segredo da maria', 'A1', 'Maria'));
        const other = { ...incoming('mensagem do joao', 'B1', 'Joao'), key: { remoteJid: '5511888880000@s.whatsapp.net', fromMe: false, id: 'B1' } };
        await gw.handleMessage(other);

        const maria = (await gw.chatMemory.findRelevant('', 'Maria', 10)).map((m) => m.theirMessage);
        expect(maria).toEqual(['segredo da maria']);
    });

    it('ignores triggers sent by other people (only the owner toggles the bot)', async () => {
        await gw.handleMessage(incoming('me responde .', 'A1'));
        await gw.handleMessage(incoming('e agora?', 'A2'));

        expect(gw.getTriggerState('Maria')).toBe(false);
        expect(sock.sendMessage).not.toHaveBeenCalled();
    });

    it('owner " ." activates (JIT profile from accumulated history) and " ," pauses immediately', async () => {
        await gw.handleMessage(incoming('fala parceiro, bora jogar sabado?', 'A1'));
        await gw.handleMessage(incoming('leva o baralho', 'A2'));
        expect(gw.contacts.Maria).toBeUndefined();

        await gw.handleMessage(own('deixa comigo .', 'M1'));

        // JIT: profile generated by the LLM from the isolated history and persisted
        expect(gw.getTriggerState('Maria')).toBe(true);
        expect(readJson('trigger-states.json').Maria).toBe(true);
        expect(readJson('contacts.json').Maria).toMatchObject({ relationship: 'amigo', rules: 'seja leve', jit: true });

        await gw.handleMessage(incoming('combinado?', 'A3'));
        expect(sock.sendMessage).toHaveBeenCalledTimes(1);

        await gw.handleMessage(own(',', 'M2'));
        expect(gw.getTriggerState('Maria')).toBe(false);

        await gw.handleMessage(incoming('ta ai?', 'A4'));
        expect(sock.sendMessage).toHaveBeenCalledTimes(1);
    });

    it('falls back to a safe default profile when the LLM is unavailable', async () => {
        brain.generate.mockRejectedValue(new Error('offline'));
        await gw.handleMessage(incoming('oi', 'A1'));
        await gw.handleMessage(own('.', 'M1'));

        expect(readJson('contacts.json').Maria).toMatchObject({ relationship: 'desconhecido', jit: 'default' });
    });

    it('never reads the bot\'s own echoed replies as owner triggers', async () => {
        await gw.handleMessage(incoming('oi', 'A1'));
        await gw.handleMessage(own('.', 'M1'));
        gw.sentIds.add('ECHO-1');

        await gw.handleMessage(own('resposta do bot ,', 'ECHO-1'));
        expect(gw.getTriggerState('Maria')).toBe(true);
    });

    it('global kill-switch blocks replies but never learning', async () => {
        await gw.handleMessage(incoming('oi', 'A1'));
        await gw.handleMessage(own('.', 'M1'));
        sock.sendMessage.mockClear();
        gw._ensureDataDir();
        const flag = join(dataDir, 'RESPONSES_DISABLED');
        (await import('node:fs')).writeFileSync(flag, '');

        await gw.handleMessage(incoming('segue a conversa', 'A2'));
        expect(sock.sendMessage).not.toHaveBeenCalled();
        const memories = (await gw.chatMemory.findRelevant('', 'Maria', 10)).map((m) => m.theirMessage);
        expect(memories).toContain('segue a conversa');
        expect(existsSync(flag)).toBe(true);
    });

    it('guard only observes for activated contacts (autoSend) and still blocks otherwise', async () => {
        const leaky = new ClonePipeline({ dataDir, config: {} });
        leaky.setBrain({ generate: async () => 'As an AI language model, I cannot do that' });

        const auto = await leaky.processMessage({ text: 'oi' }, { name: 'Maria', autoSend: true });
        expect(auto.action).toBe('suppressed'); // revelacao de IA: aborta em silencio, sem fila
        expect(auto.replies).toEqual([]);

        leaky.setBrain({ generate: async () => 'beleza' });
        const ok = await leaky.processMessage({ text: 'oi' }, { name: 'Maria', autoSend: true });
        expect(ok.action).toBe('reply');

        leaky.setBrain({ generate: async () => 'As an AI language model, I cannot do that' });

        const manual = await leaky.processMessage({ text: 'oi' }, { name: 'Maria' });
        expect(manual.action).toBe('blocked');
    });

    it('trigger sovereignty: ghost-mode inactivity timer never blocks an activated chat', async () => {
        gw.ghost = { getStatus: () => ({ ghostMode: true }), shouldCloneReply: () => false };
        await gw.handleMessage(incoming('oi', 'A1'));
        await gw.handleMessage(own('.', 'M1'));
        sock.sendMessage.mockClear();
        await gw.handleMessage(incoming('responde ai', 'A2'));

        expect(sock.sendMessage).toHaveBeenCalledTimes(1);
    });

    it('owner activation has sovereignty over night hours unless OPENSELF_ENFORCE_ONLINE_HOURS=1', async () => {
        await gw.handleMessage(incoming('oi', 'A1'));
        await gw.handleMessage(own('.', 'M1'));
        sock.sendMessage.mockClear();

        // By default, owner activation is sovereign even at 03:00 BRT
        gw.now = () => new Date('2026-10-14T06:00:00Z'); // 03:00 BRT
        await gw.handleMessage(incoming('acordado?', 'A2'));
        expect(sock.sendMessage).toHaveBeenCalledTimes(1);

        // When explicitly enforced, it respects online_hours schedule
        process.env.OPENSELF_ENFORCE_ONLINE_HOURS = '1';
        try {
            await gw.handleMessage(incoming('acordado ainda?', 'A3'));
            expect(sock.sendMessage).toHaveBeenCalledTimes(1); // not called again
            const heard = (await gw.chatMemory.findRelevant('', 'Maria', 10)).map((m) => m.theirMessage);
            expect(heard).toContain('acordado ainda?');
        } finally {
            delete process.env.OPENSELF_ENFORCE_ONLINE_HOURS;
        }
    });

    it.each([
        ['tudo bem.', 'A1'],
        ['tudo bem,', 'A2'],
        ['ok...', 'A3'],
        ['ok ..', 'A4'],
        ['1.5', 'A5'],
        ['..', 'A6'],
    ])('plain text %j sent by the owner never activates the bot', async (text, id) => {
        await gw.handleMessage(incoming('oi', 'IN-' + id));
        await gw.handleMessage(own(text, id));
        expect(gw.getTriggerState('Maria')).toBe(false);
    });

    it.each([
        ['deixa comigo .', true],
        ['.', true],
        [' . ', true],
    ])('owner trigger %j activates', async (text) => {
        await gw.handleMessage(incoming('oi', 'A1'));
        await gw.handleMessage(own(text, 'M1'));
        expect(gw.getTriggerState('Maria')).toBe(true);
    });

    it('aborts silently (nothing sent) when the reply reveals the AI, in pt-BR', async () => {
        await gw.handleMessage(incoming('oi', 'A1'));
        await gw.handleMessage(own('.', 'M1'));
        sock.sendMessage.mockClear();

        for (const leak of [
            'como uma IA eu nao tenho sentimentos',
            'sou um assistente virtual',
            'como um modelo de linguagem nao posso',
            'nao tenho sentimentos, mas ta',
        ]) {
            brain.generate.mockImplementation(async () => leak);
            await gw.handleMessage(incoming('tudo bem? ' + leak.length, 'L' + leak.length));
        }
        expect(sock.sendMessage).not.toHaveBeenCalled();
        expect(await gw.pipeline.chatMemory.findRelevant('', 'Maria', 50)).not.toContainEqual(
            expect.objectContaining({ yourReply: expect.stringMatching(/IA|assistente|linguagem|sentimentos/) }),
        );
    });

    it('aborts silently when the reply leaks a password or token', async () => {
        await gw.handleMessage(incoming('oi', 'A1'));
        await gw.handleMessage(own('.', 'M1'));
        sock.sendMessage.mockClear();

        for (const leak of ['a senha do wifi eh abc12345', 'token: ghp_' + 'a'.repeat(30), 'gsk_' + 'b'.repeat(24)]) {
            brain.generate.mockImplementation(async () => leak);
            await gw.handleMessage(incoming('me passa? ' + leak.length, 'S' + leak.length));
        }
        expect(sock.sendMessage).not.toHaveBeenCalled();
    });

    it('removes assistant-speak in pt-BR instead of suppressing and still replies', async () => {
        await gw.handleMessage(incoming('oi', 'A1'));
        await gw.handleMessage(own('.', 'M1'));
        sock.sendMessage.mockClear();
        brain.generate.mockImplementation(async () => 'beleza! Como posso te ajudar?');
        await gw.handleMessage(incoming('e ai', 'A2'));

        expect(sock.sendMessage).toHaveBeenCalledTimes(1);
        const replyText = sock.sendMessage.mock.calls[0][1].text;
        expect(replyText).not.toMatch(/como posso te ajudar/i);
        expect(replyText.length).toBeGreaterThan(0);
    });

    it('silent takeover: owner sending "." with pending messages triggers bot reply to pending text without calling learnFromSelf', async () => {
        await gw.handleMessage(incoming('preciso de som pra festa', 'P1'));
        await gw.handleMessage(incoming('quanto fica?', 'P2'));
        sock.sendMessage.mockClear();

        // Owner sends silent trigger " ."
        await gw.handleMessage(own('.', 'M_SILENT'));

        expect(gw.getTriggerState('Maria')).toBe(true);
        expect(sock.sendMessage).toHaveBeenCalledTimes(1);
        expect(brain.generate).toHaveBeenCalledWith(
            expect.any(String),
            'preciso de som pra festa\nquanto fica?'
        );
    });

    it('text with trigger: owner sending "Vou ver aqui ." records via learnFromSelf and does not trigger bot reply', async () => {
        await gw.handleMessage(incoming('tem vaga pra hoje?', 'V1'));
        sock.sendMessage.mockClear();

        // Owner sends text + trigger
        await gw.handleMessage(own('Vou ver aqui .', 'M_TEXT'));

        expect(gw.getTriggerState('Maria')).toBe(true);
        // Owner replied, so bot should not send a message
        expect(sock.sendMessage).not.toHaveBeenCalled();
        const memories = await gw.chatMemory.findRelevant('', 'Maria', 10);
        expect(memories.some(m => m.yourReply === 'Vou ver aqui')).toBe(true);
    });

    it('third party message with trigger symbols never alters trigger state or calls processTriggers', async () => {
        const spyProcess = vi.spyOn(gw, 'processTriggers');
        await gw.handleMessage(incoming('quero comprar .', 'C1'));

        expect(spyProcess).not.toHaveBeenCalled();
        expect(gw.getTriggerState('Maria')).toBe(false);
        expect(sock.sendMessage).not.toHaveBeenCalled();
        spyProcess.mockRestore();
    });

    it('sanitizes accidental trailing period or comma from LLM output before sending', async () => {
        await gw.handleMessage(own('.', 'M_ACT'));
        sock.sendMessage.mockClear();
        brain.generate.mockImplementation(async () => 'Tranquilo meu querido .');

        await gw.handleMessage(incoming('consegue fazer?', 'C2'));
        expect(sock.sendMessage).toHaveBeenCalledTimes(1);
        const sentText = sock.sendMessage.mock.calls[0][1].text;
        expect(sentText.toLowerCase()).toContain('querido');
        expect(sentText).not.toMatch(/\s+[.,]$/);
    });

    it('feed (dedupe) re-runs are idempotent and keep identical same-day messages distinct', async () => {
        const conv = (n) => ({ contact: '~Neia', theirMessage: 'kkkk', yourReply: 'ok', date: '01/01/2026', time: '10:00', n });
        await gw.chatMemory.indexHistory([conv(1), conv(2), conv(3)], { dedupe: true });
        await gw.chatMemory.indexHistory([conv(1), conv(2), conv(3)], { dedupe: true });
        expect(gw.chatMemory.getStats().totalMemories).toBe(3);
    });

    it('contacts.json keys saved as "~Nome" match the normalized key', async () => {
        gw._ensureDataDir();
        (await import('node:fs')).writeFileSync(
            join(dataDir, 'contacts.json'),
            JSON.stringify({ '~Maria': { relationship: 'amiga', rules: 'x' } }),
        );
        gw.loadContacts();
        expect(gw.contacts.Maria.relationship).toBe('amiga');
    });
});

describe('WhatsAppGateway — message batching (burst => one reply)', () => {
    let root, dataDir, gw, sock, brain;
    const wait = (ms) => new Promise((r) => setTimeout(r, ms));

    beforeEach(async () => {
        root = mkdtempSync(join(tmpdir(), 'openself-batch-'));
        dataDir = join(root, 'data');
        brain = { generate: vi.fn(async () => 'beleza') };
        const pipeline = new ClonePipeline({ dataDir, config: {} });
        pipeline.setBrain(brain);
        gw = new WhatsAppGateway({
            dataDir,
            sessionDir: join(dataDir, 'whatsapp-session'),
            pipeline,
            ghost: { getStatus: () => ({ ghostMode: false }), shouldCloneReply: () => true },
        });
        pipeline.setMemory(gw.conversationMemory, gw.chatMemory);
        sock = {
            user: { id: 'me@s.whatsapp.net' },
            readMessages: vi.fn(async () => {}),
            presenceSubscribe: vi.fn(async () => {}),
            sendPresenceUpdate: vi.fn(async () => {}),
            sendMessage: vi.fn(async () => ({ key: { id: 'BOT-' + Math.random() } })),
        };
        gw.sock = sock;
        gw.sleep = async () => {};
        gw.now = () => new Date('2026-10-14T15:00:00Z');
        gw.batchMinMs = 40;
        gw.batchMaxMs = 60;
        gw.batchCapMs = 1000;
        await gw.handleMessage(incoming('oi', 'A0'));
        await gw.handleMessage(own('.', 'M0'));
        await wait(200);
        brain.generate.mockClear();
        sock.sendMessage.mockClear();
    });

    afterEach(() => rmSync(root, { recursive: true, force: true }));

    it('merges 3 rapid messages into a single LLM call and a single reply', async () => {
        await gw.handleMessage(incoming('oi', 'B1'));
        await gw.handleMessage(incoming('tudo bem?', 'B2'));
        await gw.handleMessage(incoming('preciso de um orcamento', 'B3'));
        expect(sock.sendMessage).not.toHaveBeenCalled();

        await wait(250);

        expect(brain.generate).toHaveBeenCalledTimes(1);
        expect(brain.generate.mock.calls[0][1]).toBe('oi\ntudo bem?\npreciso de um orcamento');
        expect(sock.sendMessage).toHaveBeenCalledTimes(1);
    });

    it('still learns every message of the burst individually (RAG)', async () => {
        await gw.handleMessage(incoming('primeira', 'B1'));
        await gw.handleMessage(incoming('segunda', 'B2'));
        const heard = (await gw.chatMemory.findRelevant('', 'Maria', 20)).map((m) => m.theirMessage);
        expect(heard).toEqual(expect.arrayContaining(['primeira', 'segunda']));
        await wait(250);
    });

    it('collapses the burst into one entry in the conversation context', async () => {
        await gw.handleMessage(incoming('msg um', 'B1'));
        await gw.handleMessage(incoming('msg dois', 'B2'));
        await wait(250);
        const ctx = gw.conversationMemory.getRecentContext('Maria', 10);
        expect(ctx).toContain('Maria: msg um\nmsg dois');
        expect(ctx.match(/msg um/g)).toHaveLength(1);
        expect(ctx).toContain('You: beleza');
    });

    it('cancels the queued reply when the owner writes in the chat first', async () => {
        await gw.handleMessage(incoming('me responde', 'B1'));
        await gw.handleMessage(own('ja vou ai', 'M1'));
        await wait(250);
        expect(sock.sendMessage).not.toHaveBeenCalled();
    });

    it('does not send if the owner pauses the bot (" ,") before the window closes', async () => {
        await gw.handleMessage(incoming('e ai', 'B1'));
        await gw.handleMessage(own(',', 'M1'));
        await wait(250);
        expect(sock.sendMessage).not.toHaveBeenCalled();
    });

    it('messages arriving after the reply was sent start a new batch', async () => {
        await gw.handleMessage(incoming('primeira', 'B1'));
        await wait(250);
        await gw.handleMessage(incoming('segunda', 'B2'));
        await wait(250);
        expect(sock.sendMessage).toHaveBeenCalledTimes(2);
    });
});
